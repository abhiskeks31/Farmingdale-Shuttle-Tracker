package com.farmingdale.shuttle.entity;

import jakarta.persistence.*;
import java.time.OffsetDateTime;

// Represents a service announcement posted by an administrator
@Entity
@Table(name = "alert")
public class Alert {

    // Unique ID for each alert
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "alert_id")
    private Long alertId;

    // Short heading describing the alert
    @Column(name = "title", nullable = false, length = 150)
    private String title;

    // Full message displayed to students
    @Column(name = "message", nullable = false, columnDefinition = "TEXT")
    private String message;

    // INFO, DELAY, CANCELLATION, or EMERGENCY
    @Column(name = "alert_type", nullable = false, length = 20)
    private String alertType = "INFO";

    // Automatically generated by PostgreSQL
    @Column(name = "created_at", nullable = false,
            insertable = false, updatable = false)
    private OffsetDateTime createdAt;

    // Optional date and time when the alert expires
    @Column(name = "expires_at")
    private OffsetDateTime expiresAt;

    // Whether the administrator has enabled this alert
    @Column(name = "is_active", nullable = false)
    private Boolean isActive = true;

    // ID of the administrator who created the alert
    @Column(name = "created_by")
    private Long createdBy;

    // Required constructor for JPA
    public Alert() {
    }

    // Getters and setters

    public Long getAlertId() {
        return alertId;
    }

    public void setAlertId(Long alertId) {
        this.alertId = alertId;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }

    public String getAlertType() {
        return alertType;
    }

    public void setAlertType(String alertType) {
        this.alertType = alertType;
    }

    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    public OffsetDateTime getExpiresAt() {
        return expiresAt;
    }

    public void setExpiresAt(OffsetDateTime expiresAt) {
        this.expiresAt = expiresAt;
    }

    public Boolean getIsActive() {
        return isActive;
    }

    public void setIsActive(Boolean isActive) {
        this.isActive = isActive;
    }

    public Long getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(Long createdBy) {
        this.createdBy = createdBy;
    }
}
