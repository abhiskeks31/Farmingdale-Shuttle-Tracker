CREATE TABLE public.trip_feedback_session (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    trip_id BIGINT NOT NULL
        REFERENCES public.trip(trip_id),

    shuttle_id BIGINT NOT NULL
        REFERENCES public.shuttle(shuttle_id),

    driver_id INTEGER NOT NULL
        REFERENCES public.driver(driver_id),

    verification_code VARCHAR(12) NOT NULL UNIQUE,

    completed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    expires_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT feedback_expiry_check
        CHECK (expires_at > completed_at)
);

-- Prevent direct access through public Supabase clients.
ALTER TABLE public.trip_feedback_session
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.trip_feedback_session
FROM anon, authenticated;

REVOKE ALL ON SEQUENCE
public.trip_feedback_session_session_id_seq
FROM anon, authenticated;


ALTER TABLE public.driver_feedback
ADD COLUMN session_id BIGINT
    REFERENCES public.trip_feedback_session(session_id);

CREATE INDEX idx_driver_feedback_session
ON public.driver_feedback(session_id);
