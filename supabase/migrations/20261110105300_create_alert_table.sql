
CREATE TABLE public.alert (
    alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    title VARCHAR(150) NOT NULL,
    message TEXT NOT NULL,

    alert_type VARCHAR(20) NOT NULL DEFAULT 'INFO',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_by BIGINT REFERENCES public.admin(admin_id)
        ON DELETE SET NULL,

    CONSTRAINT alert_type_check
        CHECK (alert_type IN (
            'INFO',
            'DELAY',
            'CANCELLATION',
            'EMERGENCY'
        )),

    CONSTRAINT alert_title_not_blank
        CHECK (LENGTH(TRIM(title)) > 0),

    CONSTRAINT alert_message_not_blank
        CHECK (LENGTH(TRIM(message)) > 0)
);

-- Enable Row Level Security.
ALTER TABLE public.alert ENABLE ROW LEVEL SECURITY;

-- Do not expose direct database access to browser clients.
REVOKE ALL ON TABLE public.alert FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.alert_alert_id_seq
    FROM anon, authenticated;

-- Improve retrieval of active announcements.
CREATE INDEX idx_alert_active_created
ON public.alert (created_at DESC)
WHERE is_active = TRUE;
